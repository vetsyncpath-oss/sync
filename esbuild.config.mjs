// Follow obsidianmd/obsidian-sample-plugin: CommonJS entry beside manifest.json,
// host-provided modules external, ES2021 output and a persistent dev watcher.
import { context } from 'esbuild';
import { builtinModules } from 'node:module';
import { readFileSync } from 'node:fs';
import { writeStyles } from './scripts/styles.mjs';

const production = process.argv.includes('production');
const ctx = await context({
  entryPoints: ['main.ts'],
  outfile: 'main.js',
  bundle: true,
  format: 'cjs',
  target: 'es2021',
  external: [
    'obsidian', 'electron',
    '@codemirror/*', '@lezer/*',
    ...builtinModules, ...builtinModules.map(name => `node:${name}`),
  ],
  sourcemap: production ? false : 'inline',
  treeShaking: true,
  minify: production,
  banner: { js: `/* Generated by esbuild. Source: vetsyncpath-oss/sync.
Adapted Google Drive URL/query helpers: hesprs/sync-engine, a795a46abe8b6d6fc6a319152cda1b65cfc9c8b9.
${readFileSync(new URL('./licenses/sync-engine-MIT.txt', import.meta.url), 'utf8')}
*/` },
  logLevel: 'info',
  plugins: production ? [] : [{ name: 'sync-styles', setup(build) {
    build.onEnd(async result => { if (!result.errors.length) await writeStyles(); });
  } }],
});

if (production) {
  try { await ctx.rebuild(); } finally { await ctx.dispose(); }
} else {
  await ctx.watch();
  for (const signal of ['SIGINT', 'SIGTERM']) {
    process.once(signal, async () => { await ctx.dispose(); process.exit(0); });
  }
}
